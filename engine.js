  // ───────────────────────── 搶答比賽流程 ─────────────────────────
  /**
   * 一場搶答比賽。伺服器與單機都用這個類別。
   * emit(eventName, data) 會把事件送給畫面或網路。
   */
  class RushMatch {
    constructor(opts) {
      this.rounds = opts.rounds || 10;
      this.timeLimit = opts.timeLimit || 15000;
      this.types = (opts.types || RUSH_TYPES).filter((t) => MAKERS[t]);
      if (!this.types.length) this.types = RUSH_TYPES.slice();
      this.aiLevel = AI_LEVELS[opts.aiLevel] ? opts.aiLevel : 'normal';
      this.rng = makeRng(opts.seed);
      this.emit = opts.emit || function () {};
      this.players = opts.players.map((p) => ({
        id: p.id, name: p.name, ai: !!p.ai, avatar: p.avatar || '🙂', xp: p.ai ? AI_XP[opts.aiLevel] || AI_XP.normal : p.xp || 0, score: 0, correct: 0,
      }));
      this.qi = 0;
      this.phase = 'idle';
      this.timers = new Set();
      this.avoid = new Set();
      this.q = null;
      this.locked = new Set();
    }
    later(fn, ms) {
      const h = setTimeout(() => { this.timers.delete(h); fn(); }, ms);
      this.timers.add(h);
      return h;
    }
    clearTimers() { this.timers.forEach((h) => clearTimeout(h)); this.timers.clear(); }
    scores() { return this.players.map((p) => ({ id: p.id, score: p.score, correct: p.correct })); }
    start() {
      this.phase = 'countdown';
      this.emit('match_start', {
        rounds: this.rounds, timeLimit: this.timeLimit,
        players: this.players.map(({ id, name, ai, avatar, xp }) => ({ id, name, ai, avatar, xp })),
      });
      this.later(() => this.next(), 3200);
    }
    next() {
      if (this.qi >= this.rounds) return this.finish();
      const type = this.types[Math.floor(this.rng() * this.types.length)];
      this.q = makeQuestion(type, this.rng, 4, this.avoid);
      this.qi++;
      this.locked = new Set();
      this.phase = 'question';
      this.qStart = Date.now();
      this.qLimit = (TYPE_TIME[type] || 15) * 1000;
      this.emit('question', { index: this.qi, total: this.rounds, timeLimit: this.qLimit, q: publicQuestion(this.q) });
      const lv = AI_LEVELS[this.aiLevel]; const slow = this.qLimit / 15000;
      this.players.filter((p) => p.ai).forEach((p) => {
        const delay = (lv.min + this.rng() * (lv.max - lv.min)) * slow;
        const ok = this.rng() < lv.acc;
        const qid = this.q.id;
        this.later(() => {
          if (!this.q || this.q.id !== qid) return;
          let choice = this.q.answer;
          if (!ok) {
            const wrong = this.q.options.map((_, i) => i).filter((i) => i !== this.q.answer);
            choice = wrong[Math.floor(this.rng() * wrong.length)];
          }
          this.answer(p.id, choice);
        }, delay);
      });
      this.qTimer = this.later(() => this.reveal(null, 0), this.qLimit);
    }
    answer(pid, choice) {
      if (this.phase !== 'question' || this.locked.has(pid)) return;
      const p = this.players.find((x) => x.id === pid);
      if (!p) return;
      if (choice === this.q.answer) {
        const elapsed = Date.now() - this.qStart;
        const pts = 100 + Math.max(0, Math.round(50 * (1 - elapsed / this.qLimit)));
        p.score += pts; p.correct++;
        this.reveal(pid, pts);
      } else {
        this.locked.add(pid);
        p.score = Math.max(0, p.score - 20);
        this.emit('wrong', { id: pid, choice, scores: this.scores() });
        if (this.locked.size >= this.players.length) this.reveal(null, 0);
      }
    }
    reveal(winner, pts) {
      if (this.phase !== 'question') return;
      this.phase = 'reveal';
      this.clearTimers();
      const q = this.q;
      this.emit('reveal', {
        winner, pts, answer: q.answer, idiom: q.idiom, meaning: q.meaning, type: q.type,
        fix: q.type === 'error' ? q.idiom[q.answer] : undefined, scores: this.scores(),
        extra: q.type === 'history' ? q.items : undefined,
      });
      this.later(() => this.next(), 3000);
    }
    finish() {
      this.phase = 'ended';
      this.clearTimers();
      const ranking = this.players.slice().sort((a, b) => b.score - a.score || b.correct - a.correct)
        .map((p, i) => ({ rank: i + 1, id: p.id, name: p.name, ai: p.ai, avatar: p.avatar, xp: p.xp, score: p.score, correct: p.correct }));
      this.ranking = ranking;
      this.emit('match_end', { ranking });
    }
    stop() { this.phase = 'ended'; this.clearTimers(); }
    /** 中途重新連線時用的目前狀態 */
    snapshot() {
      return {
        phase: this.phase, index: this.qi, total: this.rounds, timeLimit: this.timeLimit,
        remain: this.phase === 'question' ? Math.max(0, this.qLimit - (Date.now() - this.qStart)) : 0, timeLimit: this.qLimit,
        q: this.phase === 'question' && this.q ? publicQuestion(this.q) : null,
        locked: [...this.locked],
        players: this.players.map(({ id, name, ai, avatar, xp }) => ({ id, name, ai, avatar, xp })),
        scores: this.scores(),
      };
    }
  }


