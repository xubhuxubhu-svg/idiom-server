  /** 連連看：產生 n 組成語，拆成「前兩字」與「後兩字」 */
  function makeLinkBoard(rng, n = 8) {
    const chosen = []; const halves = new Set();
    let guard = 0;
    while (chosen.length < n && guard++ < 500) {
      const it = pick(rng, IDIOMS);
      const a = it.w.slice(0, 2), b = it.w.slice(2);
      if (halves.has(a) || halves.has(b) || a === b) continue;
      halves.add(a); halves.add(b); chosen.push(it);
    }
    let id = 0;
    const tiles = [];
    chosen.forEach((it, k) => {
      tiles.push({ id: id++, t: it.w.slice(0, 2), half: 0, group: k });
      tiles.push({ id: id++, t: it.w.slice(2), half: 1, group: k });
    });
    return { idioms: chosen, tiles: shuffle(rng, tiles) };
  }
  function linkPair(a, b) {
    const w1 = a.t + b.t, w2 = b.t + a.t;
    if (BY_WORD.has(w1)) return BY_WORD.get(w1);
    if (BY_WORD.has(w2)) return BY_WORD.get(w2);
    return null;
  }

